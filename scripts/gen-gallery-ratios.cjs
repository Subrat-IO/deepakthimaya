// Generates src/content/gallery-ratios.ts (width / height of every gallery image)
// so gallery tiles reserve their exact box before images load (no layout shift).
// Re-run after adding gallery images:  node scripts/gen-gallery-ratios.cjs
const fs = require("fs");
const path = require("path");
const sizeOf = require("next/dist/compiled/image-size");

const root = path.resolve(__dirname, "..");
const sources = ["src/content/gallery-data.ts", "src/content/gallery-recent-uploads.ts"];
const srcs = new Set();
for (const file of sources) {
  const text = fs.readFileSync(path.join(root, file), "utf8");
  for (const m of text.matchAll(/src:\s*"([^"]+)"/g)) srcs.add(m[1]);
  // sep16() helper in gallery-recent-uploads.ts
  for (const m of text.matchAll(/sep16\((\d*)\)/g)) {
    srcs.add(m[1] === "" ? "/images/WhatsApp Image 2026-09-16 at 18.27.24.jpeg" : `/images/WhatsApp Image 2026-09-16 at 18.27.24 (${m[1]}).jpeg`);
  }
}

const out = {};
const missing = [];
for (const src of [...srcs].sort()) {
  const file = path.join(root, "public", decodeURI(src));
  try {
    const dim = sizeOf(fs.readFileSync(file));
    let { width, height } = dim;
    if (dim.orientation && dim.orientation >= 5) [width, height] = [height, width];
    if (width && height) out[src] = Math.round((width / height) * 1000) / 1000;
  } catch {
    missing.push(src);
  }
}

const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
const ts = `// AUTO-GENERATED by scripts/gen-gallery-ratios.cjs - do not edit by hand.\n// width / height of each gallery image, used to reserve tile space before load.\nexport const galleryRatios: Record<string, number> = {\n${body}\n};\n`;
fs.writeFileSync(path.join(root, "src/content/gallery-ratios.ts"), ts, "utf8");
console.log(`ratios: ${Object.keys(out).length}, missing: ${missing.length}`);
if (missing.length) console.log(missing.join("\n"));
